import { chromium } from '/home/ytani/.local/lib/playwright/node_modules/playwright/index.mjs';
const shot = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
const dialogs = [];
page.on('dialog', d => { dialogs.push(d.message()); d.dismiss(); });
page.on('requestfailed', r => errors.push('requestfailed: ' + r.url().slice(0, 80) + ' ' + r.failure()?.errorText));
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') errors.push('console.error: ' + m.text()); });
let aborted = 0;
await page.route('**/api.rss2json.com/**', r => { aborted++; r.abort(); });
await page.goto('http://localhost:8080/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
const newsOpts = await page.$$eval('#optgroup-news option', os => os.map(o => ({ value: o.value, text: o.textContent })));
console.log('aborted rss requests =', aborted);
console.log('optgroup-news options =', JSON.stringify(newsOpts));
const allPresetCount = await page.$$eval('#preset-select option', os => os.length);
console.log('preset-select total options =', allPresetCount);
await page.selectOption('#preset-select', 'news-summary');
await page.waitForTimeout(800);
const author = await page.textContent('#article-author');
const display = await page.evaluate(() => document.getElementById('text-display').textContent);
console.log('after select: author box =', author);
console.log('text-display head =', JSON.stringify(display.slice(0, 200)));
const heads = [...display.matchAll(/【ニュース(\d)】([^\n]*)/g)].map(m => m[1] + ':' + m[2].slice(0, 60));
console.log('bracket headings in display =', JSON.stringify(heads));
await page.screenshot({ path: shot, fullPage: false });
console.log('dialogs =', JSON.stringify(dialogs));
console.log('errors =', JSON.stringify(errors));
await browser.close();
